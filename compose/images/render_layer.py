#!/usr/bin/env python3
"""
Write the Dockerfile of one service's compose layer.

    python3 compose/images/render_layer.py <service>      # Dockerfile on stdout

The layer sits on top of the application's own image, built unchanged from
systems/<service>/Dockerfile (the BASE). It is generated rather than kept as a
file because of one Docker rule: a Dockerfile that sets ENTRYPOINT resets the
CMD it inherited. The anyuid layer needs an entrypoint, so it must repeat the
base's CMD - and a copy kept by hand would drift the first time the application
changed a gunicorn flag. Read from the application's Dockerfile at build time,
it cannot.

The service table is compose/images/services.json.
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SOURCE_URL = 'https://github.com/izelpii/airlock'

LABELS = '''ARG AIRLOCK_VERSION=unknown
ARG AIRLOCK_REVISION=unknown
LABEL org.opencontainers.image.title="Airlock Photos - {name}" \\
      org.opencontainers.image.source="{source}" \\
      org.opencontainers.image.version="${{AIRLOCK_VERSION}}" \\
      org.opencontainers.image.revision="${{AIRLOCK_REVISION}}" \\
      org.opencontainers.image.licenses="LicenseRef-Airlock-Personal-NonCommercial" \\
      org.opencontainers.image.description="Part of the Airlock Photos compose install - see compose/README.md"
'''


def services():
    with open(os.path.join(HERE, 'services.json'), encoding='utf-8') as fh:
        return json.load(fh)['services']


def base_cmd(source):
    """
    The CMD of the application's Dockerfile, as a JSON array.

    The LAST CMD in the file: in a multi-stage build that is the final stage's,
    which is the one the image runs. Continuation lines are joined first, since
    several Dockerfiles spread a long exec-form CMD over lines.
    """
    path = os.path.join(REPO, source, 'Dockerfile')
    with open(path, encoding='utf-8') as fh:
        text = fh.read()
    joined = re.sub(r'\\\n', ' ', text)
    cmds = [line.strip()[3:].strip() for line in joined.splitlines()
            if re.match(r'^\s*CMD\s', line)]
    if not cmds:
        raise SystemExit(f'{path}: no CMD')
    cmd = json.loads(cmds[-1])          # exec form only; a shell-form CMD is refused
    if not isinstance(cmd, list) or not all(isinstance(c, str) for c in cmd):
        raise SystemExit(f'{path}: CMD is not an exec-form JSON array')
    return cmd


def has_entrypoint(source):
    with open(os.path.join(REPO, source, 'Dockerfile'), encoding='utf-8') as fh:
        return any(re.match(r'^\s*ENTRYPOINT\s', line) for line in fh)


def _fetch(item):
    """A RUN that downloads one file and refuses it unless the SHA-256 matches.
    Python, because every anyuid image has it and not every one has curl."""
    dest = item['dest']
    script = ('import hashlib, os, sys, urllib.request; '
              f'd = {dest!r}; os.makedirs(os.path.dirname(d), exist_ok=True); '
              f'b = urllib.request.urlopen({item["url"]!r}, timeout=120).read(); '
              f'h = hashlib.sha256(b).hexdigest(); '
              f'sys.exit("checksum mismatch for " + d + ": " + h) if h != {item["sha256"]!r} else None; '
              'open(d, "wb").write(b)')
    return (f'# {os.path.basename(dest)}, checked against its SHA-256.\n'
            f'RUN python3 -c {json.dumps(script)} && chown -R 1000:1000 {os.path.dirname(dest)}\n')


def render(name):
    table = services()
    if name not in table:
        raise SystemExit(f'unknown service {name!r}; known: {", ".join(sorted(table))}')
    svc = table[name]
    shown = svc.get('publish_as', name)
    labels = LABELS.format(name=shown, source=SOURCE_URL)
    layer = svc['layer']

    if layer == 'plain':
        return f'ARG BASE_IMAGE\nFROM ${{BASE_IMAGE}}\n{labels}'

    if layer == 'anyuid':
        if has_entrypoint(svc['source']):
            # The wrapper would replace it silently. Stop instead.
            raise SystemExit(f'{svc["source"]}/Dockerfile has an ENTRYPOINT; the anyuid '
                             'layer would replace it - extend render_layer.py first')
        owned = ' '.join(svc['owned'])
        cmd = json.dumps(base_cmd(svc['source']))
        fetches = ''.join(_fetch(f) for f in svc.get('fetch', []))
        return f'''ARG BASE_IMAGE
FROM ${{BASE_IMAGE}}
{labels}
# Generated by compose/images/render_layer.py from {svc["source"]}/Dockerfile.
USER root
COPY common/airlock-anyuid /usr/local/bin/airlock-anyuid
RUN chmod 0755 /usr/local/bin/airlock-anyuid
{fetches}ENV HOME={svc["home"]} \\
    AIRLOCK_OWNED_DIRS="{owned}"
ENTRYPOINT ["/usr/local/bin/airlock-anyuid"]
# The base's own command, repeated because ENTRYPOINT resets an inherited CMD.
CMD {cmd}
'''

    # gateway and certs have Dockerfiles of their own.
    with open(os.path.join(HERE, layer, 'Dockerfile'), encoding='utf-8') as fh:
        return fh.read()


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    sys.stdout.write(render(sys.argv[1]))
